function toItem(s: Seed): PortfolioItem {
  const closed = s.closedDaysAgo !== undefined;
  return {
    id: s.id,
    symbol: s.symbol,
    companyName: s.name,
    shares: s.shares,
    averageCostBasis: s.cost,
    sector: s.sector,
    industry: s.industry,
    sectorIsOverridden: false,
    isManual: false,
    manualMarketValue: null,
    addedAt: isoDateTime(-s.openedDaysAgo),
    transactionType: closed ? 'CLOSE' : 'OPEN',
    accountType: s.account,
    openDate: isoDate(-s.openedDaysAgo),
    closeDate: closed ? isoDate(-s.closedDaysAgo!) : null,
    closingPrice: closed ? s.closingPrice! : null,
    holdingRole: s.role,
    notes: s.id % 2 === 0 ? 'Reviewed after earnings; position sized per risk budget.' : null,
    decisionSource: s.decisionSource,
    decisionSourceClosed: closed ? 'Risk Control' : null,
    finalAction: s.finalAction ?? null,
    finalActionSeverity: s.finalActionSeverity ?? null,
    finalActionPriority: s.finalActionPriority ?? null,
    finalActionUpdatedAt: s.finalAction ? isoDateTime(0, 12) : null,
  };
}

