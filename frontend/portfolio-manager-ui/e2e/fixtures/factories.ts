/** Anchor for all relative dates so fixtures read naturally ("3 days ago"). */
const NOW = new Date();

/** ISO timestamp `days` days from now (negative = past). */
export function isoDateTime(days: number, hour = 14): string {
  const d = new Date(NOW);
  d.setUTCDate(d.getUTCDate() + days);
  d.setUTCHours(hour, 30, 0, 0);
  return d.toISOString();
}

/** `yyyy-MM-dd` date `days` days from now (negative = past). */
export function isoDate(days: number): string {
  return isoDateTime(days).slice(0, 10);
}

